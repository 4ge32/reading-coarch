import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const base = new URL('../ios/ReadingCoachShare/Resources/', import.meta.url);
const output = '// Generated by scripts/build-share.mjs. Mozilla Readability 0.6.0 (MPL-2.0).\n' +
  readFileSync(new URL('ThirdParty/Readability.js', base), 'utf8') + '\n' +
  readFileSync(new URL('Extraction.js', base), 'utf8');
const target = fileURLToPath(new URL('Preprocessing.js', base));
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Preprocessing.js is stale; run node scripts/build-share.mjs');
} else writeFileSync(target, output);
